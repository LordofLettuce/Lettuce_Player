# ---- dates and times, each language in its own way ---------------------------------------------------------------
MONTHS = {
    "en": ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"],
    # the months as Bede gives them (Æfterra Gēola is January)
    "ang": ["Æfterra Gēola", "Solmōnaþ", "Hrēþmōnaþ", "Ēastermōnaþ", "Þrimilcemōnaþ", "Ǣrra Līþa", "Æfterra Līþa", "Weodmōnaþ",
            "Hāligmōnaþ", "Winterfylleþ", "Blōtmōnaþ", "Ǣrra Gēola"],
    "es": ["enero", "febrero", "marzo", "abril", "mayo", "junio", "julio", "agosto", "septiembre", "octubre", "noviembre", "diciembre"],
    "de": ["Januar", "Februar", "März", "April", "Mai", "Juni", "Juli", "August", "September", "Oktober", "November", "Dezember"],
    "fr": ["janvier", "février", "mars", "avril", "mai", "juin", "juillet", "août", "septembre", "octobre", "novembre", "décembre"],
}


def formatDate(language, t):
    """The date (a time.struct_time) written the language's way"""
    day, month, year = t.tm_mday, t.tm_mon, t.tm_year
    if language in ("zh", "ja"):
        return f"{year}年{month}月{day}日"
    names = MONTHS.get(language, MONTHS["en"])
    if language == "es":
        return f"{day} de {names[month - 1]} de {year}"
    if language == "de":
        return f"{day}. {names[month - 1]} {year}"
    if language == "fr":
        return f"{day} {names[month - 1]} {year}"
    if language == "ang":
        return f"{day}. dæg {names[month - 1]}, {year}"
    return f"{names[month - 1]} {day:02d}, {year}"


def formatTime(language, t):
    """The time of day: AM / PM in English (and Old English), the 24-hour clock elsewhere"""
    if language in ("en", "ang"):
        hour = t.tm_hour % 12 or 12
        return f"{hour:02d}:{t.tm_min:02d} {'AM' if t.tm_hour < 12 else 'PM'}"
    return f"{t.tm_hour:02d}:{t.tm_min:02d}"
